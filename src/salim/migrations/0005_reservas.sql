-- Reservas (conta gráfica): metas e provisões, com aportes e usos. Não mexe no ledger nem no caixa.
CREATE TABLE reserves (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name          TEXT NOT NULL,
  kind          TEXT NOT NULL CHECK (kind IN ('goal','provision')),
  target_cents  BIGINT CHECK (target_cents IS NULL OR target_cents > 0),
  target_date   DATE,
  monthly_cents BIGINT NOT NULL CHECK (monthly_cents > 0),
  start_month   DATE NOT NULL CHECK (EXTRACT(DAY FROM start_month) = 1),
  archived      BOOLEAN NOT NULL DEFAULT false,
  CHECK ((kind = 'goal') = (target_cents IS NOT NULL AND target_date IS NOT NULL))
);
CREATE TABLE reserve_movements (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reserve_id     BIGINT NOT NULL REFERENCES reserves(id),
  movement_date  DATE NOT NULL,
  amount_cents   BIGINT NOT NULL CHECK (amount_cents <> 0),   -- aporte > 0, uso < 0
  note           TEXT,
  transaction_id BIGINT REFERENCES transactions(id)
);
