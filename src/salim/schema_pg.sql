-- Salim — schema Postgres (Neon). Mesmo modelo do schema.sql (SQLite), com tipos reais.
-- Convenções: dinheiro em centavos (BIGINT); datas em DATE; competência = mês (sempre dia 01);
-- débito > 0, crédito < 0. Erros de regra saem como integrity_constraint_violation (SQLAlchemy: IntegrityError).
-- Sem o caractere de porcentagem neste arquivo: ele é executado de uma vez, sem parâmetros.

-- 1. PLANO DE CONTAS -------------------------------------------------------
CREATE TABLE accounts (
  id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code                TEXT COLLATE "C" NOT NULL UNIQUE,       -- ordem lexicográfica estável ("C")
  name                TEXT NOT NULL,
  type                TEXT NOT NULL CHECK (type IN ('asset','liability','equity','income','expense')),
  parent_id           BIGINT REFERENCES accounts(id),
  is_group            BOOLEAN NOT NULL DEFAULT false,
  is_cash             BOOLEAN NOT NULL DEFAULT false,         -- banco/carteira: entra no fluxo de caixa
  tracks_obligations  BOOLEAN NOT NULL DEFAULT false,         -- toda partida exige um título (obligation)
  is_temporary        BOOLEAN NOT NULL DEFAULT false,         -- transição, reembolso, dívida
  closing_day         INTEGER CHECK (closing_day BETWEEN 1 AND 31),  -- só cartão
  due_day             INTEGER CHECK (due_day BETWEEN 1 AND 31),      -- só cartão
  archived            BOOLEAN NOT NULL DEFAULT false,
  CHECK (NOT (is_group AND (is_cash OR tracks_obligations)))
);

-- 2. LANÇAMENTOS (imutáveis) -------------------------------------------------
CREATE TABLE transactions (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_date    DATE NOT NULL,                  -- quando aconteceu (data do caixa, da compra...)
  description   TEXT NOT NULL,
  kind          TEXT NOT NULL DEFAULT 'general',   -- general|purchase|payment|transfer|consolidation|reversal
  reverses_id   BIGINT REFERENCES transactions(id),
  source        TEXT NOT NULL DEFAULT 'web',    -- web|telegram|mcp|openfinance
  external_ref  TEXT UNIQUE,                    -- idempotência (id do extrato, message_id do Telegram)
  created_at    TIMESTAMP NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC')
);

-- 3. TÍTULOS: fatura, boleto, parcela, dívida consolidada, reembolso ---------
CREATE TABLE obligations (
  id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_id         BIGINT NOT NULL REFERENCES accounts(id),
  kind               TEXT NOT NULL CHECK (kind IN ('invoice','bill','installment','consolidated','reimbursement','other')),
  reference          TEXT,
  counterparty       TEXT,
  due_date           DATE NOT NULL,
  closing_date       DATE,
  planned_date       DATE,
  installment_no     INTEGER,
  installment_total  INTEGER,
  created_by_tx_id   BIGINT NOT NULL REFERENCES transactions(id)
);

-- 4. PARTIDAS (imutáveis) ------------------------------------------------------
CREATE TABLE postings (
  id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  transaction_id    BIGINT NOT NULL REFERENCES transactions(id),
  account_id        BIGINT NOT NULL REFERENCES accounts(id),
  amount_cents      BIGINT NOT NULL CHECK (amount_cents <> 0),
  competence_month  DATE NOT NULL CHECK (EXTRACT(DAY FROM competence_month) = 1),
  obligation_id     BIGINT REFERENCES obligations(id),
  memo              TEXT
);
CREATE INDEX ix_postings_tx   ON postings(transaction_id);
CREATE INDEX ix_postings_acc  ON postings(account_id, competence_month);
CREATE INDEX ix_postings_obl  ON postings(obligation_id);

-- 5. ORÇAMENTO (fora do ledger; só leitura sobre ele) -------------------------
CREATE TABLE budget_lines (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_id    BIGINT NOT NULL REFERENCES accounts(id),
  month         DATE CHECK (month IS NULL OR EXTRACT(DAY FROM month) = 1),   -- NULL = mês padrão
  amount_cents  BIGINT NOT NULL CHECK (amount_cents >= 0),
  profile       TEXT NOT NULL DEFAULT 'spread' CHECK (profile IN ('lump','spread')),
  day_of_month  INTEGER CHECK (day_of_month BETWEEN 1 AND 31)
);
CREATE UNIQUE INDEX ux_budget ON budget_lines(account_id, month) NULLS NOT DISTINCT;

-- 6. FILA DE IMPORTAÇÃO ------------------------------------------------------
CREATE TABLE import_items (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_id     BIGINT NOT NULL REFERENCES accounts(id),
  external_id    TEXT NOT NULL UNIQUE,
  item_date      DATE NOT NULL,
  amount_cents   BIGINT NOT NULL CHECK (amount_cents <> 0),
  description    TEXT NOT NULL,
  status         TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','matched','booked','ignored')),
  transaction_id BIGINT REFERENCES transactions(id)
);

-- INTEGRIDADE NO BANCO ---------------------------------------------------------
CREATE FUNCTION fn_raise_immutable() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION USING MESSAGE = TG_ARGV[0], ERRCODE = 'integrity_constraint_violation';
END $$;

CREATE FUNCTION fn_posting_rules() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF (SELECT is_group FROM accounts WHERE id = NEW.account_id) THEN
    RAISE EXCEPTION USING MESSAGE = 'conta-grupo nao recebe lancamento', ERRCODE = 'integrity_constraint_violation';
  END IF;
  IF (SELECT tracks_obligations FROM accounts WHERE id = NEW.account_id) AND NEW.obligation_id IS NULL THEN
    RAISE EXCEPTION USING MESSAGE = 'conta exige titulo (obligation_id)', ERRCODE = 'integrity_constraint_violation';
  END IF;
  IF NEW.obligation_id IS NOT NULL
     AND (SELECT account_id FROM obligations WHERE id = NEW.obligation_id) <> NEW.account_id THEN
    RAISE EXCEPTION USING MESSAGE = 'titulo pertence a outra conta', ERRCODE = 'integrity_constraint_violation';
  END IF;
  RETURN NEW;
END $$;

CREATE FUNCTION fn_obl_frozen_cols() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.account_id <> OLD.account_id OR NEW.created_by_tx_id <> OLD.created_by_tx_id OR NEW.kind <> OLD.kind THEN
    RAISE EXCEPTION USING MESSAGE = 'titulo: conta, origem e tipo sao imutaveis', ERRCODE = 'integrity_constraint_violation';
  END IF;
  RETURN NEW;
END $$;

CREATE TRIGGER trg_posting_rules BEFORE INSERT ON postings
  FOR EACH ROW EXECUTE FUNCTION fn_posting_rules();
CREATE TRIGGER trg_postings_no_update BEFORE UPDATE ON postings
  FOR EACH ROW EXECUTE FUNCTION fn_raise_immutable('partida imutavel: use estorno');
CREATE TRIGGER trg_postings_no_delete BEFORE DELETE ON postings
  FOR EACH ROW EXECUTE FUNCTION fn_raise_immutable('partida imutavel: use estorno');
CREATE TRIGGER trg_tx_no_update BEFORE UPDATE ON transactions
  FOR EACH ROW EXECUTE FUNCTION fn_raise_immutable('lancamento imutavel: use estorno');
CREATE TRIGGER trg_tx_no_delete BEFORE DELETE ON transactions
  FOR EACH ROW EXECUTE FUNCTION fn_raise_immutable('lancamento imutavel: use estorno');
CREATE TRIGGER trg_obl_frozen_cols BEFORE UPDATE ON obligations
  FOR EACH ROW EXECUTE FUNCTION fn_obl_frozen_cols();
CREATE TRIGGER trg_obl_no_delete BEFORE DELETE ON obligations
  FOR EACH ROW EXECUTE FUNCTION fn_raise_immutable('titulo nao se apaga');

-- VIEWS ------------------------------------------------------------------------
-- SUM de BIGINT devolve numeric no Postgres: toda soma sai com CAST para BIGINT (senão chega Decimal ao Python).
-- Saldo natural do título (positivo = ainda devo / ainda tenho a receber)
CREATE VIEW v_obligation_balance AS
SELECT o.id AS obligation_id, o.account_id,
       CAST(COALESCE(SUM(p.amount_cents), 0)
            * CASE WHEN a.type IN ('asset','expense') THEN 1 ELSE -1 END AS BIGINT) AS balance_cents
FROM obligations o
JOIN accounts a ON a.id = o.account_id
LEFT JOIN postings p ON p.obligation_id = o.id
GROUP BY o.id, o.account_id, a.type;

-- DRE por competência (inclui o que ainda não foi pago)
CREATE VIEW v_dre AS
SELECT p.competence_month AS month, a.code AS account_code, a.type,
       CAST(SUM(p.amount_cents * CASE WHEN a.type = 'expense' THEN 1 ELSE -1 END) AS BIGINT) AS amount_cents
FROM postings p JOIN accounts a ON a.id = p.account_id
WHERE a.type IN ('income','expense')
GROUP BY p.competence_month, a.code, a.type;

-- Fluxo de caixa executado (movimento das contas de caixa por data do evento)
CREATE VIEW v_cash_executed AS
SELECT to_char(t.event_date, 'YYYY-MM') AS month, CAST(SUM(p.amount_cents) AS BIGINT) AS net_cents
FROM postings p
JOIN accounts a ON a.id = p.account_id AND a.is_cash
JOIN transactions t ON t.id = p.transaction_id
GROUP BY to_char(t.event_date, 'YYYY-MM');

-- Fluxo de caixa futuro: títulos em aberto na data planejada (ou vencimento). Saída < 0.
CREATE VIEW v_cash_future AS
SELECT o.id AS obligation_id, COALESCE(o.planned_date, o.due_date) AS expected_date,
       CAST(b.balance_cents * CASE WHEN a.type = 'liability' THEN -1 ELSE 1 END AS BIGINT) AS expected_cents
FROM obligations o
JOIN v_obligation_balance b ON b.obligation_id = o.id
JOIN accounts a ON a.id = o.account_id
WHERE b.balance_cents > 0;
